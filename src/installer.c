#ifndef BUILD_ID
#define BUILD_ID "unknown"  // build.sh passes the git version
#endif

#define LIB_NAME "librsmacfixes.dylib"
#define LOAD_PATH "@executable_path/" LIB_NAME
#define BACKUP_SUFFIX ".rs-mac-fixes-backup"
#define EXE_IN_APP "Rocksmith2014.app/Contents/MacOS"
#define KNOWN_TEXT_SIZE 0x17e7000  // __TEXT of the build the fixes were made for

static char g_macos[PATH_MAX];  // .../Rocksmith2014.app/Contents/MacOS
static char g_exe[PATH_MAX];

// ---------------------------------------------------------------- finding the game

#define APP_ID "221680"  // Rocksmith 2014 on Steam

static int is_game_dir(const char *dir) {
    char p[PATH_MAX];
    snprintf(p, sizeof p, "%s/" EXE_IN_APP "/Rocksmith2014", dir);
    return access(p, F_OK) == 0;
}

static void set_game(const char *dir) {
    snprintf(g_macos, sizeof g_macos, "%s/" EXE_IN_APP, dir);
    snprintf(g_exe, sizeof g_exe, "%s/Rocksmith2014", g_macos);
}

// Accepts the game folder, Rocksmith2014.app, its Contents/MacOS folder or the executable, so
// whatever the user drags in from Finder works.
static int use_game_path(const char *path) {
    char p[PATH_MAX];
    snprintf(p, sizeof p, "%s", path);
    size_t n = strlen(p);
    while (n > 1 && p[n - 1] == '/') p[--n] = 0;
    static const char *tails[] = {"/Rocksmith2014.app/Contents/MacOS/Rocksmith2014", "/Rocksmith2014.app/Contents/MacOS",
                                  "/Rocksmith2014.app/Contents", "/Rocksmith2014.app"};
    for (size_t i = 0; i < sizeof tails / sizeof *tails; i++) {
        size_t t = strlen(tails[i]);
        if (n > t && !strcmp(p + n - t, tails[i])) {
            p[n - t] = 0;
            break;
        }
    }
    if (!is_game_dir(p)) return 0;
    char real[PATH_MAX];
    set_game(realpath(p, real) ? real : p);
    return 1;
}

// Reads the value of the first  "key"  "value"  line in a Steam .vdf/.acf file into out,
// starting at *pos (which is advanced past it). Backslash escapes in the value are undone.
static int vdf_next(const char *text, size_t *pos, const char *key, char *out, size_t n) {
    char k[64];
    snprintf(k, sizeof k, "\"%s\"", key);
    const char *at = strstr(text + *pos, k);
    if (!at) return 0;
    const char *a = strchr(at + strlen(k), '"');
    if (!a) return 0;
    size_t o = 0;
    for (a++; *a && *a != '"' && *a != '\n'; a++) {
        if (*a == '\\' && a[1]) a++;
        if (o + 1 < n) out[o++] = *a;
    }
    out[o] = 0;
    *pos = (size_t)(a - text);
    return 1;
}

static char *read_text(const char *path) {
    FILE *f = fopen(path, "r");
    if (!f) return NULL;
    size_t cap = 1 << 16, len = 0;
    char *t = malloc(cap + 1);
    if (t) len = fread(t, 1, cap, f), t[len] = 0;
    fclose(f);
    return t;
}

// The game is in <library>/steamapps/common/<installdir>; installdir comes from the app's
// manifest (normally "Rocksmith2014").
static int try_library(const char *lib) {
    char p[PATH_MAX], dir[PATH_MAX] = "Rocksmith2014";
    snprintf(p, sizeof p, "%s/steamapps/appmanifest_" APP_ID ".acf", lib);
    char *acf = read_text(p);
    size_t pos = 0;
    if (acf) vdf_next(acf, &pos, "installdir", dir, sizeof dir);
    free(acf);
    snprintf(p, sizeof p, "%s/steamapps/common/%s", lib, dir);
    if (is_game_dir(p)) return set_game(p), 1;
    snprintf(p, sizeof p, "%s/steamapps/common/Rocksmith2014", lib);
    return is_game_dir(p) ? (set_game(p), 1) : 0;
}

// Steam lists its libraries in libraryfolders.vdf as lines like:  "path"  "/Volumes/Games".
// Libraries on drives that aren't connected are skipped (they can't be patched anyway).
static int find_game(void) {
    const char *home = getenv("HOME");
    if (!home) return 0;
    char steam[PATH_MAX], p[PATH_MAX], lib[PATH_MAX];
    snprintf(steam, sizeof steam, "%s/Library/Application Support/Steam", home);
    if (try_library(steam)) return 1;
    static const char *lists[] = {"steamapps/libraryfolders.vdf", "config/libraryfolders.vdf"};
    for (size_t i = 0; i < sizeof lists / sizeof *lists; i++) {
        snprintf(p, sizeof p, "%s/%s", steam, lists[i]);
        char *vdf = read_text(p);
        if (!vdf) continue;
        size_t pos = 0;
        int found = 0;
        while (!found && vdf_next(vdf, &pos, "path", lib, sizeof lib)) found = try_library(lib);
        free(vdf);
        if (found) return 1;
    }
    static const char *others[] = {"/Applications/Rocksmith2014", "/Applications/Rocksmith 2014"};
    for (size_t i = 0; i < sizeof others / sizeof *others; i++)
        if (is_game_dir(others[i])) return set_game(others[i]), 1;
    snprintf(p, sizeof p, "%s/Applications/Rocksmith2014", home);
    return is_game_dir(p) ? (set_game(p), 1) : 0;
}

// Asks for the game folder; dragging a folder from Finder into Terminal types its path, quoted
// or with backslash-escaped spaces, plus a trailing space.
static int ask_game(void) {
    for (;;) {
        printf("Drag the Rocksmith2014 folder (or Rocksmith2014.app) into this window and press Return,\n"
               "or just press Return to quit.\n> ");
        fflush(stdout);
        char line[PATH_MAX + 16], path[PATH_MAX];
        if (!fgets(line, sizeof line, stdin)) return 0;
        char *s = line, *e = line + strlen(line);
        while (e > s && (e[-1] == '\n' || e[-1] == '\r' || e[-1] == ' ' || e[-1] == '\t')) *--e = 0;
        while (*s == ' ' || *s == '\t') s++;
        if (!*s) return 0;
        if ((*s == '\'' || *s == '"') && e - s >= 2 && e[-1] == *s) s++, *--e = 0;
        size_t o = 0;
        for (; *s && o + 1 < sizeof path; s++) {
            if (*s == '\\' && s[1]) s++;
            path[o++] = *s;
        }
        path[o] = 0;
        if (path[0] == '~' && path[1] == '/' && getenv("HOME")) {
            char tmp[PATH_MAX];
            snprintf(tmp, sizeof tmp, "%s%s", getenv("HOME"), path + 1);
            snprintf(path, sizeof path, "%s", tmp);
        }
        if (use_game_path(path)) {
            printf("\n");
            return 1;
        }
        printf("\n%s doesn't contain " EXE_IN_APP "/Rocksmith2014.\n\n", path);
    }
}

static int game_running(void) {
    int n = proc_listallpids(NULL, 0);
    if (n <= 0) return 0;
    pid_t *pids = calloc((size_t)n + 16, sizeof *pids);
    if (!pids) return 0;
    n = proc_listallpids(pids, (int)(((size_t)n + 16) * sizeof *pids));
    int running = 0;
    char path[PROC_PIDPATHINFO_MAXSIZE];
    for (int i = 0; i < n && !running; i++)
        if (proc_pidpath(pids[i], path, sizeof path) > 0 && !strcmp(path, g_exe)) running = 1;
    free(pids);
    return running;
}

// ---------------------------------------------------------------- files

static uint8_t *read_file(const char *path, size_t *len) {
    FILE *f = fopen(path, "rb");
    if (!f) return NULL;
    uint8_t *d = NULL;
    if (fseeko(f, 0, SEEK_END) == 0) {
        off_t n = ftello(f);
        if (n > 0 && n < (1 << 30) && fseeko(f, 0, SEEK_SET) == 0 && (d = malloc((size_t)n)) &&
            fread(d, 1, (size_t)n, f) == (size_t)n)
            *len = (size_t)n;
        else {
            free(d);
            d = NULL;
        }
    }
    fclose(f);
    return d;
}

// Writes to a temporary file in the same folder and renames it over the target, so the target
// is never half-written (and a loaded copy is never overwritten in place).
static int write_atomic(const char *path, const void *data, size_t len, mode_t mode) {
    char tmp[PATH_MAX];
    snprintf(tmp, sizeof tmp, "%s.tmp-rs-mac-fixes", path);
    int fd = open(tmp, O_WRONLY | O_CREAT | O_TRUNC, mode);
    if (fd < 0) return -1;
    const uint8_t *p = data;
    size_t left = len;
    while (left) {
        ssize_t w = write(fd, p, left);
        if (w <= 0) break;
        p += w, left -= (size_t)w;
    }
    int ok = left == 0 && fchmod(fd, mode) == 0 && fsync(fd) == 0;
    ok = close(fd) == 0 && ok;
    if (!ok || rename(tmp, path)) {
        unlink(tmp);
        return -1;
    }
    return 0;
}

static int copy_file(const char *from, const char *to) {
    size_t len = 0;
    uint8_t *d = read_file(from, &len);
    struct stat st;
    if (!d || stat(from, &st)) {
        free(d);
        return -1;
    }
    int r = write_atomic(to, d, len, st.st_mode & 07777);
    free(d);
    return r;
}

// ---------------------------------------------------------------- Mach-O load commands

typedef struct {
    uint8_t *data;
    size_t len;
    size_t base;                 // offset of the x86_64 Mach-O in the file (fat or thin)
    struct mach_header_64 *mh;
    size_t ours, ours_size;      // our load command (offset in file), if present
    size_t first_section;        // file offset of the first section's data (end of free space)
    uint64_t text_size;
} macho;

static uint32_t be32(uint32_t v) { return __builtin_bswap32(v); }

static int parse(macho *m) {
    m->base = 0;
    uint32_t magic = *(uint32_t *)m->data;
    if (magic == FAT_CIGAM) {  // fat headers are big-endian
        struct fat_header *fh = (void *)m->data;
        struct fat_arch *fa = (void *)(fh + 1);
        uint32_t n = be32(fh->nfat_arch);
        int found = 0;
        for (uint32_t i = 0; i < n && (uint8_t *)(fa + i + 1) <= m->data + m->len; i++)
            if ((cpu_type_t)be32((uint32_t)fa[i].cputype) == CPU_TYPE_X86_64) {
                m->base = be32(fa[i].offset);
                found = 1;
            }
        if (!found) return -1;
    }
    if (m->base + sizeof(struct mach_header_64) > m->len) return -1;
    m->mh = (void *)(m->data + m->base);
    if (m->mh->magic != MH_MAGIC_64 || m->mh->cputype != CPU_TYPE_X86_64) return -1;
    if (m->base + sizeof *m->mh + m->mh->sizeofcmds > m->len) return -1;
    m->ours = m->ours_size = 0;
    m->first_section = (size_t)-1;
    m->text_size = 0;
    size_t p = m->base + sizeof *m->mh;
    for (uint32_t i = 0; i < m->mh->ncmds; i++) {
        struct load_command *lc = (void *)(m->data + p);
        if (lc->cmdsize < sizeof *lc || p + lc->cmdsize > m->base + sizeof *m->mh + m->mh->sizeofcmds) return -1;
        if (lc->cmd == LC_LOAD_WEAK_DYLIB || lc->cmd == LC_LOAD_DYLIB) {
            struct dylib_command *dc = (void *)lc;
            const char *name = (const char *)lc + dc->dylib.name.offset;
            if (dc->dylib.name.offset < lc->cmdsize &&
                !strncmp(name, LOAD_PATH, lc->cmdsize - dc->dylib.name.offset)) {
                m->ours = p;
                m->ours_size = lc->cmdsize;
            }
        }
        if (lc->cmd == LC_SEGMENT_64) {
            struct segment_command_64 *sc = (void *)lc;
            if (!strcmp(sc->segname, "__TEXT")) m->text_size = sc->vmsize;
            struct section_64 *sec = (void *)(sc + 1);
            for (uint32_t s = 0; s < sc->nsects; s++)
                if (sec[s].offset && m->base + sec[s].offset < m->first_section)
                    m->first_section = m->base + sec[s].offset;
        }
        p += lc->cmdsize;
    }
    return 0;
}

static int add_command(macho *m) {
    size_t name = strlen(LOAD_PATH) + 1;
    size_t size = (sizeof(struct dylib_command) + name + 7) / 8 * 8;
    size_t at = m->base + sizeof *m->mh + m->mh->sizeofcmds;
    if (m->first_section == (size_t)-1 || at + size > m->first_section) return -1;
    for (size_t i = 0; i < size; i++)
        if (m->data[at + i]) return -1;  // not free space after all
    struct dylib_command *dc = (void *)(m->data + at);
    dc->cmd = LC_LOAD_WEAK_DYLIB;
    dc->cmdsize = (uint32_t)size;
    dc->dylib.name.offset = sizeof *dc;
    dc->dylib.timestamp = 2;
    // No minimum version: dyld before macOS 12 skips a library older than this requires.
    dc->dylib.current_version = 0x10000;
    dc->dylib.compatibility_version = 0;
    memcpy((char *)dc + sizeof *dc, LOAD_PATH, name);
    m->mh->ncmds++;
    m->mh->sizeofcmds += (uint32_t)size;
    return 0;
}

static void remove_command(macho *m) {
    size_t end = m->base + sizeof *m->mh + m->mh->sizeofcmds;
    memmove(m->data + m->ours, m->data + m->ours + m->ours_size, end - (m->ours + m->ours_size));
    memset(m->data + end - m->ours_size, 0, m->ours_size);
    m->mh->ncmds--;
    m->mh->sizeofcmds -= (uint32_t)m->ours_size;
}

static int load_exe(macho *m) {
    m->data = read_file(g_exe, &m->len);
    if (!m->data) {
        printf("Can't read %s: %s\n", g_exe, strerror(errno));
        return -1;
    }
    if (parse(m)) {
        printf("%s doesn't look like the Rocksmith 2014 Mac executable.\n", g_exe);
        free(m->data);
        return -1;
    }
    return 0;
}

static int save_exe(macho *m) {
    struct stat st;
    mode_t mode = stat(g_exe, &st) == 0 ? (st.st_mode & 07777) : 0755;
    return write_atomic(g_exe, m->data, m->len, mode);
}

// ---------------------------------------------------------------- commands

static void lib_path(char *out, size_t n) { snprintf(out, n, "%s/" LIB_NAME, g_macos); }

static int status(void) {
    macho m;
    if (load_exe(&m)) return 1;
    char lib[PATH_MAX], backup[PATH_MAX];
    lib_path(lib, sizeof lib);
    snprintf(backup, sizeof backup, "%s" BACKUP_SUFFIX, g_exe);
    int has_lib = access(lib, F_OK) == 0;
    printf("Game:     %s\n", g_macos);
    if (m.text_size != KNOWN_TEXT_SIZE)
        printf("Note:     this game build differs from the one the fixes were made for; they will stay inactive.\n");
    printf("Fixes:    %s\n", m.ours && has_lib ? "installed"
                             : m.ours            ? "partly installed (library missing; run install again)"
                             : has_lib           ? "partly installed (load command missing; run install again)"
                                                 : "not installed");
    if (access(backup, F_OK) == 0) printf("Backup:   %s\n", backup);
    free(m.data);
    return 0;
}

static int install(void) {
    macho m;
    if (load_exe(&m)) return 1;
    if (m.text_size != KNOWN_TEXT_SIZE)
        printf("Note: this game build differs from the one the fixes were made for; they will stay inactive.\n");
    char lib[PATH_MAX], backup[PATH_MAX];
    lib_path(lib, sizeof lib);
    if (write_atomic(lib, librsmacfixes_dylib, librsmacfixes_dylib_len, 0755)) {
        printf("Can't write %s: %s\n", lib, strerror(errno));
        free(m.data);
        return 1;
    }
    printf("Wrote %s\n", lib);
    if (m.ours) {
        printf("The game already loads the fixes.\n");
        free(m.data);
        return 0;
    }
    snprintf(backup, sizeof backup, "%s" BACKUP_SUFFIX, g_exe);
    if (access(backup, F_OK) != 0) {
        if (copy_file(g_exe, backup)) {
            printf("Can't back up the executable to %s: %s\n", backup, strerror(errno));
            free(m.data);
            return 1;
        }
        printf("Backed up the executable to %s\n", backup);
    }
    if (add_command(&m)) {
        printf("No room for another load command in the executable; nothing changed in it.\n");
        free(m.data);
        return 1;
    }
    int r = save_exe(&m);
    free(m.data);
    if (r) {
        printf("Can't write %s: %s\n", g_exe, strerror(errno));
        return 1;
    }
    printf("The game now loads the fixes. Start it from Steam as usual.\n");
    return 0;
}

static int uninstall(void) {
    macho m;
    if (load_exe(&m)) return 1;
    int r = 0;
    if (m.ours) {
        remove_command(&m);
        if (save_exe(&m)) {
            printf("Can't write %s: %s\n", g_exe, strerror(errno));
            r = 1;
        } else {
            printf("Removed the load command from the executable.\n");
        }
    } else {
        printf("The executable doesn't load the fixes.\n");
    }
    free(m.data);
    char lib[PATH_MAX];
    lib_path(lib, sizeof lib);
    if (!r && access(lib, F_OK) == 0) {
        if (unlink(lib)) {
            printf("Can't remove %s: %s\n", lib, strerror(errno));
            r = 1;
        } else {
            printf("Removed %s\n", lib);
        }
    }
    return r;
}

