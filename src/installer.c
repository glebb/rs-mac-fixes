// Writes s with the home folder shown as ~, so reports can be shared without the user name.
static void put_tilde(FILE *out, const char *s) {
    const char *home = getenv("HOME");
    size_t hn = home ? strlen(home) : 0;
    while (*s) {
        if (hn > 1 && !strncmp(s, home, hn)) {
            fputc('~', out);
            s += hn;
        } else {
            fputc(*s++, out);
        }
    }
}

static void field(FILE *out, const char *label, const char *fmt, ...) __attribute__((format(printf, 3, 4)));
static void field(FILE *out, const char *label, const char *fmt, ...) {
    char buf[PATH_MAX + 256];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof buf, fmt, ap);
    va_end(ap);
    fprintf(out, "%-14s", label);
    put_tilde(out, buf);
    fputc('\n', out);
}

static const char *sysctl_str(const char *name, char *out, size_t n) {
    if (sysctlbyname(name, out, &n, NULL, 0)) snprintf(out, n, "?");
    return out;
}

static int sysctl_int(const char *name) {
    int v = 0;
    size_t n = sizeof v;
    return sysctlbyname(name, &v, &n, NULL, 0) ? 0 : v;
}

static const char *when(time_t t, char *out, size_t n) {
    strftime(out, n, "%Y-%m-%d %H:%M:%S", localtime(&t));
    return out;
}

static const char *arch_name(cpu_type_t t) {
    return t == CPU_TYPE_X86_64 ? "x86_64" : t == CPU_TYPE_ARM64 ? "arm64" : t == CPU_TYPE_I386 ? "i386" : "other";
}

static const char *version(uint32_t v, char *out, size_t n) {
    snprintf(out, n, "%u.%u.%u", v >> 16, (v >> 8) & 0xff, v & 0xff);
    return out;
}

// Returns the library version our load command requires, or -1 if there is none.
static int64_t report_exe(FILE *out, const char *lib) {
    struct stat st;
    char t[32];
    if (stat(g_exe, &st)) {
        field(out, "Executable:", "can't read: %s", strerror(errno));
        return -1;
    }
    field(out, "Executable:", "%lld bytes, changed %s", (long long)st.st_size, when(st.st_mtime, t, sizeof t));
    macho m;
    m.data = read_file(g_exe, &m.len);
    if (!m.data || m.len < 8) {
        field(out, "", "can't read: %s", strerror(errno));
        free(m.data);
        return -1;
    }
    char archs[128] = "";
    if (*(uint32_t *)m.data == FAT_CIGAM) {
        struct fat_header *fh = (void *)m.data;
        struct fat_arch *fa = (void *)(fh + 1);
        for (uint32_t i = 0; i < be32(fh->nfat_arch) && (uint8_t *)(fa + i + 1) <= m.data + m.len; i++)
            snprintf(archs + strlen(archs), sizeof archs - strlen(archs), "%s%s", i ? ", " : "",
                     arch_name((cpu_type_t)be32((uint32_t)fa[i].cputype)));
    } else if (*(uint32_t *)m.data == MH_MAGIC_64) {
        snprintf(archs, sizeof archs, "%s", arch_name(((struct mach_header_64 *)m.data)->cputype));
    }
    field(out, "", "architectures: %s", archs[0] ? archs : "unknown");
    if (parse(&m)) {
        field(out, "", "x86_64 code not readable as a Mach-O");
        free(m.data);
        return -1;
    }
    field(out, "", "__TEXT size 0x%llx (%s)", (unsigned long long)m.text_size,
         m.text_size == KNOWN_TEXT_SIZE ? "the build the fixes were made for" : "a different build");
    // The libraries the game loads, apart from the system's (so other mods show), and whether it is signed.
    size_t p = m.base + sizeof *m.mh;
    int signed_exe = 0;
    for (uint32_t i = 0; i < m.mh->ncmds; i++) {
        struct load_command *lc = (void *)(m.data + p);
        if (lc->cmd == LC_CODE_SIGNATURE) signed_exe = 1;
        if (lc->cmd == LC_LOAD_DYLIB || lc->cmd == LC_LOAD_WEAK_DYLIB) {
            struct dylib_command *dc = (void *)lc;
            const char *name = (char *)lc + dc->dylib.name.offset;
            if (dc->dylib.name.offset < lc->cmdsize && strncmp(name, "/System/", 8) && strncmp(name, "/usr/lib/", 9))
                field(out, "", "loads %.*s%s", (int)(lc->cmdsize - dc->dylib.name.offset),
                     (char *)lc + dc->dylib.name.offset, lc->cmd == LC_LOAD_WEAK_DYLIB ? " (weak)" : "");
        }
        p += lc->cmdsize;
    }
    field(out, "", "code signature: %s", signed_exe ? "yes" : "none");
    field(out, "Fixes:", "%s", m.ours && access(lib, F_OK) == 0 ? "installed"
                              : m.ours                      ? "partly installed (library missing)"
                              : access(lib, F_OK) == 0      ? "partly installed (load command missing)"
                                                            : "not installed");
    int64_t required = m.ours ? ((struct dylib_command *)(m.data + m.ours))->dylib.compatibility_version : -1;
    free(m.data);
    return required;
}

// required: what report_exe returned. dyld before macOS 12 skips a library older than that.
static void report_lib(FILE *out, const char *lib, int64_t required) {
    struct stat st;
    char t[32];
    if (stat(lib, &st)) {
        field(out, "Library:", "not there");
        return;
    }
    size_t len = 0;
    uint8_t *d = read_file(lib, &len);
    int same = d && len == librsmacfixes_dylib_len && !memcmp(d, librsmacfixes_dylib, len);
    int64_t provided = -1;
    const struct mach_header_64 *mh = (const void *)d;
    if (d && len >= sizeof *mh && mh->magic == MH_MAGIC_64 && sizeof *mh + mh->sizeofcmds <= len) {
        const uint8_t *p = d + sizeof *mh;
        for (uint32_t i = 0; i < mh->ncmds && provided < 0; i++, p += ((const struct load_command *)p)->cmdsize)
            if (((const struct load_command *)p)->cmd == LC_ID_DYLIB)
                provided = ((const struct dylib_command *)p)->dylib.compatibility_version;
    }
    free(d);
    field(out, "Library:", "%lld bytes, written %s, %s", (long long)st.st_size, when(st.st_mtime, t, sizeof t),
         same ? "same as this installer's" : "differs from this installer's (run install to update)");
    char a[16], b[16];
    if (required >= 0 && provided >= 0)
        field(out, "", "version %s, the game requires %s%s", version((uint32_t)provided, a, sizeof a),
             version((uint32_t)required, b, sizeof b),
             provided < required ? ": older macOS won't load it (run install to update)" : "");
}

static const char *quarantine(const char *path) {
    if (access(path, F_OK)) return "missing";
    return getxattr(path, "com.apple.quarantine", NULL, 0, 0, 0) >= 0 ? "quarantined" : "not quarantined";
}

// The end of the log (the last 64 KB, from a line start).
static void report_log(FILE *out, const char *log, const char *lib) {
    struct stat st, ls;
    char t[32];
    if (stat(log, &st)) {
        field(out, "Log:", "none. The game hasn't loaded the fixes yet (they create the log as soon as they load).");
        return;
    }
    field(out, "Log:", "%lld bytes, last written %s", (long long)st.st_size, when(st.st_mtime, t, sizeof t));
    if (stat(lib, &ls) == 0 && ls.st_mtime > st.st_mtime)
        field(out, "", "older than the library: the game hasn't loaded the fixes since they were installed");
    FILE *f = fopen(log, "r");
    if (!f) return;
    const long tail = 64 * 1024;
    int skip = st.st_size > tail && fseeko(f, st.st_size - tail, SEEK_SET) == 0;
    char buf[1024];
    fprintf(out, "\n---- log%s\n", skip ? " (last part)" : "");
    if (skip && !fgets(buf, sizeof buf, f)) buf[0] = 0;  // drop the partial first line
    while (fgets(buf, sizeof buf, f)) put_tilde(out, buf);
    fclose(f);
    fprintf(out, "---- end of log\n");
}

static int report(int interactive) {
    const char *home = getenv("HOME");
    if (!home) home = "/tmp";
    char path[PATH_MAX], dir[PATH_MAX], lib[PATH_MAX], log[PATH_MAX], p[PATH_MAX];
    snprintf(path, sizeof path, "%s/Desktop/rs-mac-fixes-report.txt", home);
    FILE *out = fopen(path, "w");
    if (!out) {
        snprintf(path, sizeof path, "%s/rs-mac-fixes-report.txt", home);
        out = fopen(path, "w");
    }
    if (!out) {
        printf("Can't write %s: %s\n", path, strerror(errno));
        return 1;
    }
    char os[32], build[32], cpu[128], model[64], t[32];
    int arm = sysctl_int("hw.optional.arm64");
    fprintf(out, "rs-mac-fixes report\n\n");
    field(out, "Written:", "%s", when(time(NULL), t, sizeof t));
    field(out, "Installer:", "%s", BUILD_ID);
    field(out, "macOS:", "%s (%s)", sysctl_str("kern.osproductversion", os, sizeof os),
         sysctl_str("kern.osversion", build, sizeof build));
    field(out, "Mac:", "%s, %s, %s", arm ? "Apple Silicon" : "Intel", sysctl_str("hw.model", model, sizeof model),
         sysctl_str("machdep.cpu.brand_string", cpu, sizeof cpu));
    if (arm)
        field(out, "Rosetta:", "%s",
             access("/Library/Apple/usr/libexec/oah/libRosettaRuntime", F_OK) == 0 ? "installed" : "not found");
    fputc('\n', out);
    lib_path(lib, sizeof lib);
    field(out, "Game:", "%s", g_macos);
    field(out, "Running:", "%s", game_running() ? "yes" : "no");
    report_lib(out, lib, report_exe(out, lib));
    snprintf(p, sizeof p, "%s" BACKUP_SUFFIX, g_exe);
    field(out, "Backup:", "%s", access(p, F_OK) == 0 ? "yes" : "no");
    field(out, "Quarantine:", "executable %s, library %s", quarantine(g_exe), quarantine(lib));
    fputc('\n', out);
    snprintf(dir, sizeof dir, "%s/Library/Application Support/rs-mac-fixes", home);
    snprintf(p, sizeof p, "%s/disabled", dir);
    field(out, "Disabled:", "%s", access(p, F_OK) == 0 ? "yes (the disabled file exists)" : "no");
    snprintf(p, sizeof p, "%s/budget_ms", dir);
    char *budget = read_text(p);
    if (budget) budget[strcspn(budget, "\r\n")] = 0;
    field(out, "budget_ms:", "%s", budget ? budget : "not set (50)");
    free(budget);
    snprintf(log, sizeof log, "%s/rs-mac-fixes.log", dir);
    report_log(out, log, lib);
    int r = fclose(out) ? 1 : 0;
    printf("Wrote the report to %s\n", path);
    printf("Please attach this file to your bug report. It doesn't include your user name.\n");
    if (interactive) {  // show it in Finder, ready to drag into a browser
        pid_t pid = fork();
        if (pid == 0) {
            execl("/usr/bin/open", "open", "-R", path, (char *)NULL);
            _exit(127);
        }
        if (pid > 0) waitpid(pid, NULL, 0);
    }
    return r;
}

static void usage(void) {
    printf("usage: rs-mac-fixes [install | uninstall | status | report] [--game <Rocksmith2014 folder or .app>]\n");
}

int main(int argc, char **argv) {
    const char *cmd = NULL, *game = NULL;
    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--game") && i + 1 < argc) game = argv[++i];
        else if (!strcmp(argv[i], "-h") || !strcmp(argv[i], "--help")) return usage(), 0;
        else if (!cmd) cmd = argv[i];
        else return usage(), 2;
    }
    if (cmd && strcmp(cmd, "install") && strcmp(cmd, "uninstall") && strcmp(cmd, "status") && strcmp(cmd, "report"))
        return usage(), 2;
    printf("Rocksmith 2014 Mac Fixes (%s)\n\n", BUILD_ID);
    int interactive = !cmd;
    if (game) {
        if (!use_game_path(game)) {
            printf("%s doesn't contain " EXE_IN_APP "/Rocksmith2014\n", game);
            return 1;
        }
    } else if (!find_game()) {
        printf("Rocksmith 2014 wasn't found in your Steam libraries (is the drive it's on connected?).\n");
        if (!isatty(STDIN_FILENO)) {
            printf("Run this again with: --game <path to the Rocksmith2014 folder>\n");
            return 1;
        }
        printf("\n");
        if (!ask_game()) return 1;
    }
    if (interactive) {
        status();
        printf("\n[i] install or update   [u] uninstall   [r] bug report   [q] quit\n> ");
        fflush(stdout);
        char in[16] = "";
        if (!fgets(in, sizeof in, stdin)) return 0;
        char c = (char)(in[0] | 0x20);
        cmd = c == 'i' ? "install" : c == 'u' ? "uninstall" : c == 'r' ? "report" : NULL;
        if (!cmd) return 0;
        printf("\n");
    }
    if (strcmp(cmd, "status") && strcmp(cmd, "report") && game_running()) {
        printf("Rocksmith 2014 is running. Quit it first, then run this again.\n");
        return 1;
    }
    int r = !strcmp(cmd, "install")     ? install()
            : !strcmp(cmd, "uninstall") ? uninstall()
            : !strcmp(cmd, "report")    ? report(interactive)
                                        : status();
    if (interactive) {
        printf("\nPress Return to close.");
        fflush(stdout);
        char line[16];
        if (!fgets(line, sizeof line, stdin)) return r;
    }
    return r;
}
